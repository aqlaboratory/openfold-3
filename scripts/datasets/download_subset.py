#!/usr/bin/env python3
"""Create (if needed) and download a subset of PDB training data.

If the subset cache file for the requested size doesn't exist yet
(training_cache_with_templates_subset_{train_size}.json /
validation_cache_with_templates_subset_{val_size}.json), it is generated by
randomly sampling --train-cache / --val-cache (the full, unsampled caches).
If those don't exist locally either, they are downloaded from S3 first.

Downloading happens in two phases:
  1. Target structures, alignment arrays, and templates.
  2. Reference mol SDFs -- downloaded individually for only the CCD codes
     actually needed, determined by scanning the residue composition of the
     structures downloaded in phase 1 (rather than syncing the full
     reference_mols directory, ~68k files). This two-phase split is required
     because a structure's residues can include non-standard/modified
     residues (e.g. a modified cysteine like CME) that aren't listed
     anywhere in the dataset cache and can only be discovered by inspecting
     the downloaded structure itself.

A run_openfold training runner yaml pointed at the resulting subset is also
written out (see --runner-yaml).

Usage:
    python download_subset.py                    # create+download default 32/16 subset
    python download_subset.py --train-size 128 --val-size 32
    python download_subset.py --verify            # check all files exist (no download)
    python download_subset.py --output-dir /data/foo  # download into a custom directory
    python download_subset.py --runner-yaml /data/foo/train.yaml
"""

import argparse
import sys
from pathlib import Path

from pdb_subset_helpers import (
    AMINO_ACID_CCD_CODES,
    STANDARD_NUCLEOTIDE_CCD_CODES,
    build_reference_mol_manifest,
    build_structure_manifest,
    download_full_cache,
    download_manifest,
    extract_ids_from_cache,
    sample_subset_cache,
    scan_structure_residue_names,
    structure_file_path,
    verify_manifest,
    write_runner_yaml,
)

ROOT_DIR = Path(__file__).parent
DEFAULT_OUTPUT_DIR = ROOT_DIR / "pdb_training_set"
DEFAULT_TRAIN_CACHE = ROOT_DIR / "training_cache_with_templates.json"
DEFAULT_VAL_CACHE = ROOT_DIR / "validation_cache_with_templates.json"
DEFAULT_RUNNER_YAML = ROOT_DIR / "train_pdb_subset.yaml"


def get_or_create_subset_cache(full_cache: Path, size: int, seed: int) -> Path:
    """Return the path to a size-N subset cache, generating it if missing.

    If the full cache itself isn't present locally either, it's downloaded
    from S3 first.
    """
    subset_path = ROOT_DIR / f"{full_cache.stem}_subset_{size}.json"
    if subset_path.exists():
        return subset_path

    download_full_cache(full_cache)
    sample_subset_cache(full_cache, [size], ROOT_DIR, seed=seed)
    return subset_path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--verify", action="store_true", help="Only verify, don't download"
    )
    parser.add_argument(
        "--workers", type=int, default=8, help="Parallel download threads"
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=DEFAULT_OUTPUT_DIR,
        help=f"Directory to download files into (default: {DEFAULT_OUTPUT_DIR})",
    )
    parser.add_argument(
        "--train-size", type=int, default=32, help="Train subset size (default: 32)"
    )
    parser.add_argument(
        "--val-size", type=int, default=16, help="Validation subset size (default: 16)"
    )
    parser.add_argument(
        "--train-cache",
        type=Path,
        default=DEFAULT_TRAIN_CACHE,
        help=(
            "Full training cache to sample --train-size from if the subset "
            f"cache doesn't already exist (default: {DEFAULT_TRAIN_CACHE})"
        ),
    )
    parser.add_argument(
        "--val-cache",
        type=Path,
        default=DEFAULT_VAL_CACHE,
        help=(
            "Full validation cache to sample --val-size from if the subset "
            f"cache doesn't already exist (default: {DEFAULT_VAL_CACHE})"
        ),
    )
    parser.add_argument(
        "--seed", type=int, default=42, help="Random seed for subset sampling"
    )
    parser.add_argument(
        "--runner-yaml",
        type=str,
        default=str(DEFAULT_RUNNER_YAML),
        help=(
            "Where to write a run_openfold training runner yaml pointed at the "
            f"downloaded subset (default: {DEFAULT_RUNNER_YAML}). Pass an empty "
            "string to skip writing it."
        ),
    )
    args = parser.parse_args()
    local_root = args.output_dir

    cache_files = {
        "train": get_or_create_subset_cache(
            args.train_cache, args.train_size, args.seed
        ),
        "val": get_or_create_subset_cache(args.val_cache, args.val_size, args.seed),
    }

    if args.runner_yaml:
        write_runner_yaml(Path(args.runner_yaml), cache_files, local_root)

    # Phase 1: structures, alignment arrays, templates (everything except
    # reference mols, which depend on what's actually in the structures).
    structure_manifest = []
    all_pdb_ids = set()
    cache_declared_ref_mols = set()

    for split, cache_path in cache_files.items():
        print("cache_path:", cache_path)

        template_cache_subdir = (
            "train_template_cache" if split == "train" else "val_template_cache"
        )
        ids = extract_ids_from_cache(cache_path)
        manifest = build_structure_manifest(ids, template_cache_subdir, local_root)

        print(f"\n{split} ({cache_path.name}):")
        print(f"  PDB IDs: {len(ids['pdb_ids'])}")
        print(f"  Alignment rep IDs: {len(ids['alignment_rep_ids'])}")
        print(f"  Template IDs: {len(ids['template_ids'])}")
        print(f"  Files to download: {len(manifest)}")

        structure_manifest.extend(manifest)
        all_pdb_ids |= ids["pdb_ids"]
        cache_declared_ref_mols |= ids["reference_mol_ids"]

    # Deduplicate (alignment arrays shared between train/val)
    seen = set()
    deduped = []
    for s3_key, local_path in structure_manifest:
        if s3_key not in seen:
            seen.add(s3_key)
            deduped.append((s3_key, local_path))
    structure_manifest = deduped
    print(
        f"\nTotal unique structure/alignment/template files: "
        f"{len(structure_manifest)}"
    )

    structure_paths = [
        structure_file_path(pdb_id, local_root) for pdb_id in all_pdb_ids
    ]

    if args.verify:
        missing = verify_manifest(structure_manifest)

        if all(p.exists() for p in structure_paths):
            ref_mol_ids = (
                scan_structure_residue_names(structure_paths)
                | cache_declared_ref_mols
                | AMINO_ACID_CCD_CODES
                | STANDARD_NUCLEOTIDE_CCD_CODES
            )
            ref_manifest = build_reference_mol_manifest(ref_mol_ids, local_root)
            print(f"Reference mol IDs (from structure scan): {len(ref_mol_ids)}")
            missing += verify_manifest(ref_manifest)
        else:
            print(
                "NOTE: not all target structures are downloaded yet, so "
                "reference-mol completeness can't be verified (which ones "
                "are needed depends on the actual residue composition of "
                "the downloaded structures)."
            )

        if missing:
            print(f"\nMISSING {len(missing)} files:")
            for m in missing[:20]:
                print(f"  {m}")
            if len(missing) > 20:
                print(f"  ... and {len(missing) - 20} more")
            sys.exit(1)
        else:
            print("\nAll files present!")
            sys.exit(0)

    counts = download_manifest(structure_manifest, workers=args.workers)
    print(
        f"\nStructures/alignments/templates: {counts['downloaded']} downloaded, "
        f"{counts['skipped']} skipped, {counts['failed']} failed"
    )

    # Phase 2: reference mols, determined from the actual residue composition
    # of the structures just downloaded (plus the cache-declared ligand ids
    # and the standard amino acid / nucleotide codes as a safety net).
    ref_mol_ids = (
        scan_structure_residue_names(structure_paths)
        | cache_declared_ref_mols
        | AMINO_ACID_CCD_CODES
        | STANDARD_NUCLEOTIDE_CCD_CODES
    )
    print(f"\nReference mol IDs (from structure scan): {len(ref_mol_ids)}")
    ref_manifest = build_reference_mol_manifest(ref_mol_ids, local_root)
    ref_counts = download_manifest(ref_manifest, workers=args.workers)
    print(
        f"Reference mols: {ref_counts['downloaded']} downloaded, "
        f"{ref_counts['skipped']} skipped, {ref_counts['failed']} failed"
    )

    total_downloaded = counts["downloaded"] + ref_counts["downloaded"]
    total_skipped = counts["skipped"] + ref_counts["skipped"]
    total_failed = counts["failed"] + ref_counts["failed"]
    print(
        f"\nDone: {total_downloaded} downloaded, "
        f"{total_skipped} skipped, {total_failed} failed"
    )


if __name__ == "__main__":
    main()
